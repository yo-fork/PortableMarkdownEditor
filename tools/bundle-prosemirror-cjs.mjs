import { existsSync } from 'node:fs';
import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const bundlePath = path.join(root, 'vendor', 'prosemirror', 'prosemirror-editor.js');
const integrationPath = path.join(root, 'vendor', 'prosemirror', 'editor-integration.js');
const lockPath = path.join(root, 'vendor', 'prosemirror', 'package-lock.json');
const integrationMarker = "  var model = requireModule('prosemirror-model');";
const wrapperEnd = '\n})(window);';
const generatedHeader = '// Generated by tools/bundle-prosemirror-cjs.mjs. Do not edit by hand.\n';
const packageNames = [
  'orderedmap',
  'prosemirror-model',
  'prosemirror-transform',
  'prosemirror-state',
  'prosemirror-view',
  'w3c-keyname',
  'rope-sequence',
  'prosemirror-keymap',
  'prosemirror-commands',
  'prosemirror-history',
  'prosemirror-inputrules',
  'prosemirror-dropcursor',
  'prosemirror-gapcursor',
  'prosemirror-schema-basic',
  'prosemirror-schema-list',
  'prosemirror-markdown',
  'prosemirror-tables',
];

function optionValue(name) {
  const index = process.argv.indexOf(name);
  if (index < 0) return '';
  const value = process.argv[index + 1];
  if (!value || value.startsWith('--')) throw new Error(`${name} requires a path`);
  return value;
}

function resolveFromRoot(value) {
  return path.isAbsolute(value) ? path.resolve(value) : path.resolve(root, value);
}

function integrationFromBundle(bundle) {
  const start = bundle.indexOf(integrationMarker);
  const end = bundle.lastIndexOf(wrapperEnd);
  if (start < 0 || end <= start) throw new Error('ProseMirror integration boundary was not found');
  return `${bundle.slice(start, end).trimEnd()}\n`;
}

function dependencyPrefixFromBundle(bundle) {
  const wrapperStart = bundle.indexOf('(function(global)');
  const integrationStart = bundle.indexOf(integrationMarker);
  if (wrapperStart < 0 || integrationStart <= wrapperStart) {
    throw new Error('ProseMirror dependency-module boundary was not found');
  }
  return bundle.slice(wrapperStart, integrationStart);
}

async function extractIntegration() {
  if (existsSync(integrationPath) && !process.argv.includes('--force')) {
    throw new Error('editor-integration.js already exists; pass --force to replace it');
  }
  const bundle = await readFile(bundlePath, 'utf8');
  await writeFile(integrationPath, integrationFromBundle(bundle), 'utf8');
  console.log(`Extracted ${path.relative(root, integrationPath).replaceAll(path.sep, '/')}`);
}

async function readIntegration() {
  const integration = await readFile(integrationPath, 'utf8');
  if (!integration.startsWith(integrationMarker)) {
    throw new Error('editor-integration.js must start at the documented integration marker');
  }
  if (integration.includes('(function(global)') || integration.includes('})(window);')) {
    throw new Error('editor-integration.js must not contain the generated wrapper');
  }
  return `${integration.trimEnd()}\n`;
}

async function buildWithBundledModules(integration) {
  const currentBundle = await readFile(bundlePath, 'utf8');
  const dependencyPrefix = dependencyPrefixFromBundle(currentBundle);
  return `${generatedHeader}${dependencyPrefix}${integration.trimEnd()}${wrapperEnd}\n`;
}

function requiredSpecifiers(code) {
  const specifiers = new Set();
  const pattern = /\brequire\s*\(\s*['"]([^'"]+)['"]\s*\)/g;
  let match;
  while ((match = pattern.exec(code)) !== null) specifiers.add(match[1]);
  return [...specifiers];
}

async function readPackageModule(name, nodeModulesRoot, lock) {
  const packageDirectory = path.join(nodeModulesRoot, name);
  const packageJsonPath = path.join(packageDirectory, 'package.json');
  const packageJson = JSON.parse(await readFile(packageJsonPath, 'utf8'));
  const lockedVersion = lock.packages?.[`node_modules/${name}`]?.version;
  if (!lockedVersion || packageJson.version !== lockedVersion) {
    throw new Error(`${name} version does not match vendor/prosemirror/package-lock.json`);
  }
  const entryPath = path.join(packageDirectory, packageJson.main || 'index.js');
  const code = (await readFile(entryPath, 'utf8')).trimEnd();
  const unsupportedDependencies = requiredSpecifiers(code).filter(
    (specifier) => specifier !== 'markdown-it' && !packageNames.includes(specifier),
  );
  if (unsupportedDependencies.length) {
    throw new Error(`${name} has unbundled dependencies: ${unsupportedDependencies.join(', ')}`);
  }
  return { name, code };
}

async function buildFromInstalledPackages(integration, nodeModulesRoot) {
  const lock = JSON.parse(await readFile(lockPath, 'utf8'));
  const packageModules = [];
  for (const name of packageNames) {
    packageModules.push(await readPackageModule(name, nodeModulesRoot, lock));
  }
  const definitions = packageModules
    .map(({ name, code }) => `    ${JSON.stringify(name)}: function(require, module, exports) {\n${code}\n    }`)
    .join(',\n');

  return `${generatedHeader}(function(global) {
  'use strict';
  var modules = {
${definitions}
  };
  var cache = Object.create(null);
  function requireModule(name) {
    if (name === 'markdown-it') {
      var MarkdownIt = global.markdownit || global.markdownIt;
      if (!MarkdownIt) throw new Error('markdown-it is required before ProseMirror Markdown support');
      return MarkdownIt;
    }
    if (!modules[name]) throw new Error('Missing ProseMirror module: ' + name);
    if (cache[name]) return cache[name].exports;
    var module = cache[name] = { exports: {} };
    modules[name](requireModule, module, module.exports);
    return module.exports;
  }

${integration.trimEnd()}${wrapperEnd}
`;
}

async function writeOrCheck(output) {
  if (process.argv.includes('--check')) {
    const current = await readFile(bundlePath, 'utf8');
    if (current !== output) throw new Error('prosemirror-editor.js is not synchronized with its generated source');
    console.log('ProseMirror bundle is synchronized');
    return;
  }
  await writeFile(bundlePath, output, 'utf8');
  console.log(`Wrote ${path.relative(root, bundlePath).replaceAll(path.sep, '/')}`);
}

if (process.argv.includes('--extract-integration')) {
  await extractIntegration();
} else {
  const integration = await readIntegration();
  const reuseBundledModules = process.argv.includes('--reuse-bundled-modules');
  const configuredNodeModules = optionValue('--node-modules');
  const nodeModulesRoot = configuredNodeModules
    ? resolveFromRoot(configuredNodeModules)
    : path.join(root, 'vendor', 'prosemirror', 'node_modules');
  const output = reuseBundledModules
    ? await buildWithBundledModules(integration)
    : await buildFromInstalledPackages(integration, nodeModulesRoot);
  await writeOrCheck(output);
}
