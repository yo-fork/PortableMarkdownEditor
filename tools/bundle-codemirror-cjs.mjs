import { readFile, writeFile } from 'node:fs/promises';
import { createRequire } from 'node:module';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const nodeModulesRoot = path.join(root, 'vendor', 'codemirror6', 'node_modules');
const sourceEditorPath = path.join(root, 'vendor', 'codemirror6', 'source-editor.js');
const outputPath = path.join(root, 'vendor', 'codemirror6', 'source-editor.bundle.js');
const requireFromScript = createRequire(import.meta.url);
const requirePattern = /\brequire\s*\(\s*['"]([^'"]+)['"]\s*\)/g;
const entryId = 'virtual:source-editor';

const modules = new Map();

function toBundleId(filePath) {
  return path.relative(root, filePath).replaceAll(path.sep, '/');
}

function resolveModule(specifier, fromFile) {
  const paths = fromFile
    ? [path.dirname(fromFile), nodeModulesRoot]
    : [nodeModulesRoot];
  try {
    return requireFromScript.resolve(specifier, { paths });
  } catch (error) {
    if (specifier === 'w3c-keyname' && error?.code === 'MODULE_NOT_FOUND') {
      return path.join(nodeModulesRoot, 'w3c-keyname', 'index.js');
    }
    throw error;
  }
}

function transformKnownEsmDependency(filePath, code) {
  const normalized = toBundleId(filePath);
  if (normalized !== 'vendor/codemirror6/node_modules/w3c-keyname/index.js') return code;
  return code
    .replace(/\bexport var base =/, 'var base =')
    .replace(/\bexport var shift =/, 'var shift =')
    .replace(/\bexport function keyName\(/, 'function keyName(')
    + '\nexports.base = base;\nexports.shift = shift;\nexports.keyName = keyName;\n';
}

function requiredSpecifiers(code) {
  const specs = [];
  const seen = new Set();
  requirePattern.lastIndex = 0;
  let match;
  while ((match = requirePattern.exec(code)) !== null) {
    const specifier = match[1];
    if (seen.has(specifier)) continue;
    seen.add(specifier);
    specs.push(specifier);
  }
  return specs;
}

async function addFileModule(filePath) {
  const id = toBundleId(filePath);
  if (modules.has(id)) return id;

  const code = transformKnownEsmDependency(filePath, await readFile(filePath, 'utf8'));
  modules.set(id, { id, filePath, code, requires: {} });

  for (const specifier of requiredSpecifiers(code)) {
    const resolvedPath = resolveModule(specifier, filePath);
    const depId = await addFileModule(resolvedPath);
    modules.get(id).requires[specifier] = depId;
  }

  return id;
}

async function sourceEditorEntryCode() {
  const source = await readFile(sourceEditorPath, 'utf8');
  const stripped = source
    .replace(/^import[\s\S]+?from '@codemirror\/lang-markdown';\r?\n\r?\n/, '')
    .replace(/export function createPortableMarkdownSourceEditor/, 'function createPortableMarkdownSourceEditor');

  if (/\bimport\s+/.test(stripped) || /\bexport\s+/.test(stripped)) {
    throw new Error('source-editor.js contains import/export syntax the bundler did not transform');
  }

  return [
    "const { EditorSelection, EditorState } = require('@codemirror/state');",
    "const { EditorView, crosshairCursor, drawSelection, dropCursor, highlightActiveLine, highlightActiveLineGutter, keymap, lineNumbers, rectangularSelection } = require('@codemirror/view');",
    "const { defaultKeymap, history, historyKeymap, indentWithTab } = require('@codemirror/commands');",
    "const { bracketMatching, defaultHighlightStyle, foldGutter, foldKeymap, indentOnInput, syntaxHighlighting } = require('@codemirror/language');",
    "const { markdown, markdownKeymap } = require('@codemirror/lang-markdown');",
    '',
    stripped,
    '',
    'exports.createPortableMarkdownSourceEditor = createPortableMarkdownSourceEditor;',
  ].join('\n');
}

async function addEntryModule() {
  const code = await sourceEditorEntryCode();
  modules.set(entryId, { id: entryId, filePath: null, code, requires: {} });
  for (const specifier of requiredSpecifiers(code)) {
    const resolvedPath = resolveModule(specifier, null);
    const depId = await addFileModule(resolvedPath);
    modules.get(entryId).requires[specifier] = depId;
  }
}

function emitBundle() {
  const sortedModules = [...modules.values()].sort((a, b) => a.id.localeCompare(b.id));
  const moduleDefinitions = sortedModules
    .map((mod) => `${JSON.stringify(mod.id)}: function(require, module, exports) {\n${mod.code}\n}`)
    .join(',\n');
  const moduleRequireMaps = sortedModules
    .map((mod) => `${JSON.stringify(mod.id)}: ${JSON.stringify(mod.requires)}`)
    .join(',\n');

  return `// Generated by tools/bundle-codemirror-cjs.mjs. Do not edit by hand.
(function(global) {
  'use strict';

  var modules = {
${moduleDefinitions}
  };
  var moduleRequires = {
${moduleRequireMaps}
  };
  var moduleCache = {};

  function requireModule(id) {
    var cached = moduleCache[id];
    if (cached) return cached.exports;
    var factory = modules[id];
    if (!factory) throw new Error('CodeMirror bundle module not found: ' + id);
    var module = { exports: {} };
    moduleCache[id] = module;
    factory(requireFrom(id), module, module.exports);
    return module.exports;
  }

  function requireFrom(id) {
    return function(specifier) {
      var resolved = moduleRequires[id] && moduleRequires[id][specifier];
      if (!resolved) throw new Error('CodeMirror bundle dependency not found: ' + id + ' -> ' + specifier);
      return requireModule(resolved);
    };
  }

  var entry = requireModule(${JSON.stringify(entryId)});
  global.PMECodeMirrorSourceEditor = {
    createPortableMarkdownSourceEditor: entry.createPortableMarkdownSourceEditor
  };
})(typeof globalThis !== 'undefined' ? globalThis : window);
`;
}

await addEntryModule();
await writeFile(outputPath, emitBundle(), 'utf8');
console.log(`Wrote ${path.relative(root, outputPath).replaceAll(path.sep, '/')} with ${modules.size} modules`);
